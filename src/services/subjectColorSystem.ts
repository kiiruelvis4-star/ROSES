// ==========================================
// 3. COLOR RETRIEVAL HELPERS
// ==========================================

export function getStageForGrade(gradeLevel: GradeLevel): PrimaryStage {
  return gradeLevel <= 3 ? 'lower_primary' : 'upper_primary';
}

export function getSubjectColorDef(stage: PrimaryStage, colorKey: string): SubjectColorDef {
  if (stage === 'lower_primary') {
    return LOWER_PRIMARY_SUBJECT_COLORS[colorKey] || LOWER_PRIMARY_SUBJECT_COLORS.math;
  }
  return UPPER_PRIMARY_SUBJECT_COLORS[colorKey] || UPPER_PRIMARY_SUBJECT_COLORS.math;
}

export function getSubjectColorClasses(stage: PrimaryStage, colorKey: string) {
  const def = getSubjectColorDef(stage, colorKey);
  return {
    card: `${def.lightBg} ${def.lightBorder} border ${def.darkBg} ${def.darkBorder}`,
    text: `${def.lightText} ${def.darkText}`,
    badge: `${def.badgeBgLight} ${def.badgeBgDark} border px-2 py-0.5 rounded text-xs font-semibold`,
    primaryHex: def.primaryHex,
    colorName: def.colorName,
  };
}

export function getAssessmentBandClasses(band: PerformanceBand) {
  const def = ASSESSMENT_BAND_COLORS[band];
  return {
    badge: `inline-flex items-center px-2 py-0.5 rounded-full text-xs font-bold border ${def.lightBg} ${def.darkBg}`,
    text: `${def.lightText} ${def.darkText}`,
    hex: def.hex,
    label: def.label,
  };
}

